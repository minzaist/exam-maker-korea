-- Run once in Supabase Dashboard > SQL Editor.
-- The app uses a server-only Secret Key; no browser/anonymous access is granted.

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    fingerprint text unique not null,
    name text not null,
    masked_service_number text not null,
    is_admin boolean not null default false,
    consented_at timestamptz not null,
    created_at timestamptz not null
);

create table if not exists public.activities (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    created_at timestamptz not null,
    file_names jsonb not null default '[]'::jsonb,
    exam_types jsonb not null default '[]'::jsonb,
    question_count integer not null,
    title_hint text not null default '',
    additional_notes text not null default '',
    status text not null,
    result_title text not null default '',
    error_message text not null default ''
);

create index if not exists idx_activities_created_at
    on public.activities(created_at desc);
create index if not exists idx_activities_user_created
    on public.activities(user_id, created_at desc);

create table if not exists public.auth_sessions (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    token_hash text unique not null,
    created_at timestamptz not null,
    expires_at timestamptz not null,
    last_seen_at timestamptz not null,
    revoked_at timestamptz
);

create table if not exists public.login_events (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    created_at timestamptz not null,
    method text not null,
    user_agent text not null default ''
);

create index if not exists idx_auth_sessions_token on public.auth_sessions(token_hash);
create index if not exists idx_login_events_created_at on public.login_events(created_at desc);

alter table public.users enable row level security;
alter table public.activities enable row level security;
alter table public.auth_sessions enable row level security;
alter table public.login_events enable row level security;

revoke all on table public.users from anon, authenticated;
revoke all on table public.activities from anon, authenticated;
revoke all on table public.auth_sessions from anon, authenticated;
revoke all on table public.login_events from anon, authenticated;
grant all on table public.users to service_role;
grant all on table public.activities to service_role;
grant all on table public.auth_sessions to service_role;
grant all on table public.login_events to service_role;
grant usage, select on sequence public.users_id_seq to service_role;
grant usage, select on sequence public.activities_id_seq to service_role;
grant usage, select on sequence public.auth_sessions_id_seq to service_role;
grant usage, select on sequence public.login_events_id_seq to service_role;
